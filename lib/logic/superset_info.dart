/// Plain-language explanation of what a superset/circuit is, shown via an
/// info icon everywhere the concept is introduced (the plan builder, editing
/// an existing session, and execution mode's own superset card) - "superset"
/// isn't self-explanatory the way "reps" or "rest" is.
const supersetExplanationNote =
    'A superset (or circuit) groups two or more exercises to be done '
    'back-to-back, with one shared rest only after the whole group - not '
    'after each individual exercise.\n\n'
    'During a workout, the grouped exercises are done in rounds: one set of '
    'each exercise, in order, then rest, then repeat for the next round.\n\n'
    "If the exercises in a group have different numbers of sets, that's "
    'fine and handled automatically - once an exercise runs out of sets, it '
    'simply drops out of the remaining rounds while the others continue.';
